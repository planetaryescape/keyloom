// Layout (IR) -> the files of a QMK keymap folder (05#generation-writes-keymapc-configh-and-rulesmk).
// Pure: it returns text, so the same layout always gives the same bytes and the round-trip test can
// run without a filesystem.
import type { BoardDefinition } from "../../boards/schema.ts";
import type { FirmwareSetting, Layout, Passthrough } from "../../layout/schema.ts";
import { type EmitContext, bindingToC } from "./emit-binding.ts";
import { renderCombos } from "./emit-combos.ts";
import { renderKeymaps } from "./emit-keymap.ts";
import { macroCase, macroNames } from "./emit-macros.ts";
import { danceEnumName, renderTapDances } from "./emit-tap-dance.ts";
import { tappingCallbacks } from "./emit-tapping.ts";
import { qmkRevision } from "./board-config.ts";
import { GenerateError } from "./generate-error.ts";
import { WRAPPER_SYMBOL, NO_LTO, WRAP_LINK_FLAG, buildMarker, serialDefine, wrapperSource } from "./handsfree.ts";

export { GenerateError } from "./generate-error.ts";

export type GenerateInput = {
  layout: Layout;
  board: BoardDefinition;
  /** The keyloom revision the source is made from; it goes in the header so a flashed build can be traced. */
  revisionId: string;
  /** Which hardware revision's build config to read (the layout macro is the same for all of a board's today). */
  boardRevisionId?: string;
  /**
   * Makes the firmware flashable with no keypress (D-070): its USB serial number names this build, and a raw-HID
   * packet reboots it into the bootloader. Left out, the output is what Oryx's own source builds to.
   */
  handsFree?: { buildId: string };
};

export type GeneratedFile = { path: string; content: string };
export type GeneratedSource = {
  keymapName: string;
  files: GeneratedFile[];
  /** Functions the linked firmware must define, or the build is rejected (the hands-free wrapper, D-070). */
  requiredSymbols?: string[];
};

export const KEYMAP_NAME = "keyloom";

const header = (revisionId: string, comment: "//" | "#"): string => `${comment} Generated by keyloom from ${revisionId} — edit in keyloom, not here`;

/** QMK's layer_state_t is this many bits wide when config.h says so; layers past it silently never turn on. */
const LAYER_STATE_BITS: Record<string, number> = { LAYER_STATE_8BIT: 8, LAYER_STATE_16BIT: 16, LAYER_STATE_32BIT: 32 };
const MAX_LAYERS = 32;

const KNOWN_FILES = new Set(["keymap.c", "config.h", "rules.mk", "keymap.json"]);

function settingLine(s: FirmwareSetting): string {
  // Flags are defined or not; `#define X false` would still define it, so a false flag is left out.
  if (s.value === true) return `#define ${s.key}`;
  if (s.value === false) return `// ${s.key} is off, so it is not defined`;
  // Strings are C source text with their quotes (config-h.ts), so they are written as they came.
  return `#define ${s.key} ${s.value}`;
}

function checkLayers(layout: Layout): void {
  if (layout.layers.length > MAX_LAYERS) throw new GenerateError(`${layout.layers.length} layers; QMK supports at most ${MAX_LAYERS}`);
  for (const s of layout.settings) {
    const bits = LAYER_STATE_BITS[s.key];
    if (s.firmware === "qmk" && s.value === true && bits !== undefined && layout.layers.length > bits) {
      throw new GenerateError(`${s.key} limits the layout to ${bits} layers, and it has ${layout.layers.length}; layers past ${bits} would never turn on`);
    }
  }
  const ids = new Set<string>();
  for (const l of layout.layers) {
    if (ids.has(l.id)) throw new GenerateError(`two layers are called "${l.id}"`);
    ids.add(l.id);
  }
}

/** Source of the layout's passthrough in `file`, in the order the importer found it. */
const passthroughIn = (layout: Layout, file: string): Passthrough[] => layout.passthrough.filter((p) => p.firmware === "qmk" && p.file === file);

export function generateQmkSource(input: GenerateInput): GeneratedSource {
  const { layout, board } = input;
  if (board.firmware !== "qmk" || layout.firmware !== "qmk") throw new GenerateError(`${board.id} is not a QMK board`);
  if (layout.boardId !== board.id) throw new GenerateError(`the layout is for ${layout.boardId}, not ${board.id}`);
  for (const p of layout.passthrough) {
    if (p.firmware === "qmk" && !KNOWN_FILES.has(p.file)) throw new GenerateError(`passthrough for ${p.file}: keyloom only writes ${[...KNOWN_FILES].join(", ")}`);
  }
  const rev = qmkRevision(board, input.boardRevisionId);
  checkLayers(layout);
  // The wrapper replaces a function of ZSA's Oryx module; on another board the link would fail or, worse, wrap something else.
  if (input.handsFree && board.vendor !== "ZSA") throw new GenerateError(`hands-free flashing is only built for ZSA boards, not ${board.id}`);
  const marker = input.handsFree ? buildMarker(input.handsFree.buildId) : undefined;

  const ctx: EmitContext = {
    layerIndex: new Map(layout.layers.map((l, i) => [l.id, i])),
    macroNames: macroNames(layout.macros),
    tapDanceNames: new Map(layout.tapDances.map((t, i) => [t.id, danceEnumName(i)])),
  };
  const zsa = board.vendor === "ZSA";

  const keymapC = passthroughIn(layout, "keymap.c");
  // Oryx tap dance code that couldn't be read stays as written, and it already owns DANCE_n and tap_dance_actions[].
  if (layout.tapDances.length > 0 && keymapC.some((p) => p.anchor.startsWith("tap-dance"))) {
    throw new GenerateError("keymap.c keeps tap dance code from Oryx that keyloom couldn't read, so keyloom can't add tap dances beside it");
  }
  const dances = renderTapDances(layout.tapDances, layout.macros, ctx);
  const before = keymapC.filter((p) => p.anchor.startsWith("define:") || p.anchor === "tap-dance-codes");
  const cases = keymapC.filter((p) => p.anchor.startsWith("process_record_user:"));
  const rest = keymapC.filter((p) => !before.includes(p) && !cases.includes(p));
  // Oryx writes chordal_hold_layout between keymaps[] and the combos, and everything else after them.
  // Order in C only matters to the linker's layout, but keeping Oryx's makes the binary identical to Oryx's.
  const beforeCombos = rest.filter((p) => p.anchor === "chordal-hold-layout");
  const afterCombos = rest.filter((p) => p.anchor !== "chordal-hold-layout");
  const passthroughC = keymapC.map((p) => p.source).join("\n");

  const combos = renderCombos(layout, ctx, passthroughC);
  const tapping = tappingCallbacks(layout, (b) => bindingToC(b, ctx), (id) => `TD(${ctx.tapDanceNames.get(id)})`);

  // Custom keycodes: ZSA's own RGB_SLD comes first, as Oryx writes it, then one per macro.
  const names = layout.macros.map((m) => ctx.macroNames.get(m.id) as string);
  const enumEntries = zsa ? ["RGB_SLD = ZSA_SAFE_RANGE", ...names] : names.map((n, i) => (i === 0 ? `${n} = SAFE_RANGE` : n));

  const c: string[] = [header(input.revisionId, "//"), "#include QMK_KEYBOARD_H", '#include "version.h"'];
  if (zsa) {
    c.push("#define MOON_LED_LEVEL LED_LEVEL", "#ifndef ZSA_SAFE_RANGE", "#define ZSA_SAFE_RANGE SAFE_RANGE", "#endif");
  }
  if (enumEntries.length > 0) c.push("", `enum custom_keycodes {\n${enumEntries.map((e) => `  ${e},`).join("\n")}\n};`);
  if (dances) c.push("", dances.codes);
  for (const p of before) c.push("", p.source);
  c.push("", renderKeymaps(layout, board, rev.build.layoutMacro, ctx));
  for (const p of beforeCombos) c.push("", p.source);
  if (combos.source) c.push("", combos.source);
  for (const p of afterCombos) c.push("", p.source);
  if (dances) c.push("", dances.code);
  if (tapping.functions.length > 0) c.push("", ...tapping.functions.flatMap((f, i) => (i === 0 ? [f] : ["", f])));

  const macroCases = layout.macros.map((m) => macroCase(ctx.macroNames.get(m.id) as string, m));
  // Oryx's own case for modifier-wrapped mouse keys comes first, then the macros, then the rest. The compiler
  // lays the switch out in this order, so keeping it gives a binary identical to Oryx's.
  const leading = cases.filter((p) => p.anchor.startsWith("process_record_user:QK_MODS"));
  const trailing = cases.filter((p) => !leading.includes(p));
  const caseBlocks = leading.map((p) => `    ${p.source}`).concat(macroCases, trailing.map((p) => `    ${p.source}`));
  if (caseBlocks.length > 0) {
    c.push(
      "",
      "bool process_record_user(uint16_t keycode, keyrecord_t *record) {",
      "  switch (keycode) {",
      ...caseBlocks,
      "  }",
      "  return true;",
      "}",
    );
  }

  if (marker !== undefined) c.push("", wrapperSource());

  const h: string[] = [header(input.revisionId, "//")];
  for (const s of layout.settings) if (s.firmware === "qmk") h.push(settingLine(s));
  // Oryx's SERIAL_NUMBER is replaced, not redefined: a second #define would warn and the build fails on warnings.
  for (const p of passthroughIn(layout, "config.h")) if (marker === undefined || p.anchor !== "define:SERIAL_NUMBER") h.push(p.source);
  if (marker !== undefined) h.push(serialDefine(marker));
  for (const d of [...combos.defines, ...tapping.defines]) h.push(`#define ${d}`);

  const files: GeneratedFile[] = [
    { path: "keymap.c", content: `${c.join("\n")}\n` },
    { path: "config.h", content: `${h.join("\n")}\n` },
  ];

  const rules = rulesMk(layout, combos.count, layout.tapDances.length > 0, marker !== undefined);
  if (rules) files.push({ path: "rules.mk", content: rules });

  const keymapJson = passthroughIn(layout, "keymap.json")[0]?.source ?? (rev.build.modules ? `${JSON.stringify({ modules: rev.build.modules }, null, 4)}\n` : undefined);
  if (keymapJson !== undefined) files.push({ path: "keymap.json", content: keymapJson.endsWith("\n") ? keymapJson : `${keymapJson}\n` });

  return { keymapName: KEYMAP_NAME, files, ...(marker !== undefined ? { requiredSymbols: [WRAPPER_SYMBOL] } : {}) };
}

const TAP_DANCE_YES = /^\s*TAP_DANCE_ENABLE\s*[:?]?=\s*yes\b/m;
const COMBO_YES = /^\s*COMBO_ENABLE\s*[:?]?=\s*yes\b/m;

/**
 * rules.mk is the layout's passthrough, verbatim. The one thing keyloom owns in it is whether combos
 * are on: with COMBO_ENABLE and no key_combos[] the link fails, and with combos and no COMBO_ENABLE
 * they are silently dead. make takes the last assignment, so a correction is appended.
 */
function rulesMk(layout: Layout, comboCount: number, hasTapDances: boolean, handsFree: boolean): string | undefined {
  const source = passthroughIn(layout, "rules.mk")[0]?.source;
  let text = source === undefined ? "" : source.endsWith("\n") || source === "" ? source : `${source}\n`;
  const on = COMBO_YES.test(text);
  if (comboCount > 0 && !on) text += "COMBO_ENABLE = yes\n";
  if (comboCount === 0 && on) text += "# keyloom: the layout has no combos, and COMBO_ENABLE needs a key_combos[]\nCOMBO_ENABLE = no\n";
  // Same trap as combos: TAP_DANCE_ENABLE without tap_dance_actions[] doesn't link, and TD() keys do nothing without it.
  // Oryx code kept as passthrough supplies its own tap_dance_actions[], so that case is left alone.
  const keepsOryxDances = layout.passthrough.some((p) => p.firmware === "qmk" && p.file === "keymap.c" && p.anchor.startsWith("tap-dance"));
  const dancesOn = TAP_DANCE_YES.test(text);
  if (hasTapDances && !dancesOn) text += "TAP_DANCE_ENABLE = yes\n";
  if (!hasTapDances && !keepsOryxDances && dancesOn) text += "# keyloom: the layout has no tap dances, and TAP_DANCE_ENABLE needs a tap_dance_actions[]\nTAP_DANCE_ENABLE = no\n";
  if (handsFree) text += `# keyloom: route raw_hid_receive through the bootloader command (handsfree.ts)\n${WRAP_LINK_FLAG}\n${NO_LTO}\n`;
  return text === "" ? undefined : text;
}
