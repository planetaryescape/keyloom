// Layout (IR) -> glove80.keymap and glove80.conf (06#generation-writes-glove80keymap-and-glove80conf).
// Pure: it returns text, so the same layout always gives the same bytes and the round-trip test runs
// without a filesystem.
import type { BoardDefinition, Geometry } from "../../boards/schema.ts";
import type { HandsFree } from "../../boards/recipes.ts";
import type { Layout, Passthrough } from "../../layout/schema.ts";
import { missingLayerNumbers, withLayerNumbers } from "../../layout/layer-refs.ts";
import { ZMK_BEHAVIOR_LABELS } from "../../layout/firmware-names.ts";
import { BUILTIN_PROFILES } from "./builtins.ts";
import { settingLine } from "./conf.ts";
import { type EmitContext, labelOf } from "./emit-binding.ts";
import { comboNodeName, renderBuiltinOverride, renderCombo, renderConditionalLayer, renderMacro, renderProfile, renderTapDance } from "./emit-behaviors.ts";
import { renderLayers } from "./emit-keymap.ts";
import { handsFreeConf } from "./handsfree.ts";
import { BASE_INCLUDES, CONF_FILE, KEYMAP_FILE, MAX_LAYERS } from "./files.ts";
import { GenerateError } from "./generate-error.ts";

export { GenerateError } from "./generate-error.ts";

export type GenerateInput = {
  layout: Layout;
  board: BoardDefinition;
  /** Draws the bindings in the keyboard's rows. Without it they are written ten to a line. */
  geometry?: Geometry;
  /** The keyloom revision the source is made from; it goes in the header so a flashed build can be traced. */
  revisionId: string;
  /** Base name of the written files, `<name>.keymap` and `<name>.conf`; the build recipe decides it (default `glove80`). */
  keymapName?: string;
  /** For a build: puts the build's marker in the halves' USB serial numbers, so a flash can find and verify them (D-095). */
  handsFree?: { buildId: string; config: HandsFree };
};

export type GeneratedFile = { path: string; content: string };
export type GeneratedSource = { keymapName: string; files: GeneratedFile[] };

const header = (revisionId: string, comment: "//" | "#"): string => `${comment} Generated by keyloom from ${revisionId} — edit in keyloom, not here`;

// Labels ZMK's own behaviours use live in src/layout/firmware-names.ts, where the validator's
// identifier_clash warning (07#warnings) reads the same list.

const indent = (lines: readonly string[], by: number): string[] => lines.map((l) => (l === "" ? l : `${" ".repeat(by)}${l}`));

/** Blank lines between blocks, and none at the ends. */
const blocks = (parts: ReadonlyArray<readonly string[]>): string[] => parts.filter((p) => p.length > 0).flatMap((p, i) => (i === 0 ? [...p] : ["", ...p]));

const SECTIONS = ["include", "define", "cpp", "behavior", "macro", "root", "combo", "conditional", "top"] as const;

function sectionOf(p: Passthrough): (typeof SECTIONS)[number] {
  const section = SECTIONS.find((s) => p.anchor.startsWith(`${s}:`));
  if (!section) throw new GenerateError(`passthrough "${p.anchor}" in ${p.file}: keyloom doesn't know where to write that`);
  return section;
}

function checkLabels(layout: Layout): void {
  const seen = new Map<string, string>();
  const claim = (id: string, what: string) => {
    const label = labelOf(id);
    if (ZMK_BEHAVIOR_LABELS.has(label)) throw new GenerateError(`${what} "${id}" would be written as &${label}, which is a ZMK behaviour`);
    const other = seen.get(label);
    if (other) throw new GenerateError(`${what} "${id}" and ${other} would both be written as ${label}`);
    seen.set(label, `${what} "${id}"`);
  };
  for (const p of layout.holdTapProfiles) if (!BUILTIN_PROFILES.has(p.id)) claim(p.id, "the hold-tap");
  for (const m of layout.macros) claim(m.id, "the macro");
  for (const t of layout.tapDances) {
    claim(t.id, "the tap dance");
    // The hold-taps written for its hold slots take names from the same label.
    if (t.hold) claim(`${t.id}_hold`, "its hold-tap");
    if (t.tapThenHold) claim(`${t.id}_tap_hold`, "its hold-tap");
  }
}

/** Layers that kept source names with `#define NAME <number>`, where the whole body is the layer number. */
function layerDefineNames(layout: Layout): Map<string, string> {
  const names = new Map<string, string>();
  for (const p of layout.passthrough) {
    const [ref, ...more] = p.layerRefs ?? [];
    const name = p.anchor.startsWith("define:") ? p.anchor.slice("define:".length) : undefined;
    if (ref === undefined || more.length > 0 || name === undefined || names.has(ref.layerId)) continue;
    if (p.source.slice(0, ref.start).trim() === `#define ${name}` && p.source.slice(ref.end).trim() === "") names.set(ref.layerId, name);
  }
  return names;
}

export function generateZmkSource(input: GenerateInput): GeneratedSource {
  const { board } = input;
  const layout = withLayerNumbers(input.layout);
  if (board.firmware !== "zmk" || layout.firmware !== "zmk") throw new GenerateError(`${board.id} is not a ZMK board`);
  if (layout.boardId !== board.id) throw new GenerateError(`the layout is for ${layout.boardId}, not ${board.id}`);
  if (layout.layers.length > MAX_LAYERS) throw new GenerateError(`${layout.layers.length} layers; ZMK supports at most ${MAX_LAYERS}`);
  const ids = new Set<string>();
  for (const l of layout.layers) {
    if (ids.has(l.id)) throw new GenerateError(`two layers are called "${l.id}"`);
    ids.add(l.id);
  }
  for (const p of layout.passthrough) {
    if (p.firmware === "zmk" && p.file !== KEYMAP_FILE && p.file !== CONF_FILE) throw new GenerateError(`passthrough for ${p.file}: keyloom only writes ${KEYMAP_FILE} and ${CONF_FILE}`);
  }
  checkLabels(layout);

  const layerHold = new Set<string>();
  for (const layer of layout.layers) for (const b of layer.bindings) if (b.kind === "holdTap" && "layerId" in b.hold) layerHold.add(b.profileId);

  const ctx: EmitContext = {
    layerIndex: new Map(layout.layers.map((l, i) => [l.id, i])),
    layerNames: layerDefineNames(input.layout),
    profileLabels: new Map(layout.holdTapProfiles.map((p) => [p.id, labelOf(p.id)])),
    macroLabels: new Map(layout.macros.map((m) => [m.id, labelOf(m.id)])),
    tapDanceLabels: new Map(layout.tapDances.map((t) => [t.id, labelOf(t.id)])),
  };

  const kept = (section: (typeof SECTIONS)[number]) => layout.passthrough.filter((p) => p.file === KEYMAP_FILE && sectionOf(p) === section);
  const sources = (section: (typeof SECTIONS)[number]): string[][] => kept(section).map((p) => p.source.split("\n"));
  const extraIncludes = kept("include").map((p) => p.source).filter((s) => !BASE_INCLUDES.includes(s));

  const nodes = (parts: string[][]) => parts.flatMap((p, i) => (i === 0 ? p : ["", ...p]));
  const container = (name: string, head: string[], parts: string[][]): string[] =>
    parts.length === 0 ? [] : [`${name} {`, ...indent([...head, ...(head.length > 0 ? [""] : []), ...nodes(parts)], 4), "};"];

  const behaviors = container("behaviors", [], [
    ...layout.holdTapProfiles.filter((p) => !BUILTIN_PROFILES.has(p.id)).map((p) => renderProfile(p, layerHold.has(p.id))),
    ...layout.tapDances.map((t) => renderTapDance(t, ctx)),
    ...sources("behavior"),
  ]);
  const macros = container("macros", [], [...layout.macros.map(renderMacro), ...sources("macro")]);
  const comboNames = new Set<string>();
  const comboNodes = layout.combos.map((c) => {
    const name = comboNodeName(c);
    if (comboNames.has(name)) throw new GenerateError(`two combos would both be written as ${name}`);
    comboNames.add(name);
    try {
      return renderCombo(c, ctx);
    } catch (err) {
      if (err instanceof GenerateError) throw err;
      throw new GenerateError(`combo "${c.name}": ${(err as Error).message}`);
    }
  });
  const combos = container("combos", ['compatible = "zmk,combos";'], [...comboNodes, ...sources("combo")]);
  const conditionalNames = new Set<string>();
  for (const c of layout.conditionalLayers) {
    const name = c.id.replaceAll("-", "_");
    if (conditionalNames.has(name)) throw new GenerateError(`two conditional layers would both be written as ${name}`);
    conditionalNames.add(name);
  }
  const conditionals = container("conditional_layers", ['compatible = "zmk,conditional-layers";'], [
    ...layout.conditionalLayers.map((c) => renderConditionalLayer(c, ctx)),
    ...sources("conditional"),
  ]);
  const keymap = [
    "keymap {",
    '    compatible = "zmk,keymap";',
    "",
    ...indent(renderLayers(layout, board, input.geometry, ctx), 4),
    "};",
  ];

  const root = ["/ {", ...indent(blocks([behaviors, macros, ...sources("root"), combos, conditionals, keymap]), 4), "};"];
  const overrides = layout.holdTapProfiles.filter((p) => BUILTIN_PROFILES.has(p.id)).map(renderBuiltinOverride);

  const keymapText = blocks([
    [header(input.revisionId, "//")],
    [...BASE_INCLUDES, ...extraIncludes],
    kept("define").map((p) => p.source),
    sources("cpp").flat(),
    root,
    ...overrides,
    ...sources("top"),
  ]);

  const marker = input.handsFree ? handsFreeConf(input.handsFree.config, input.handsFree.buildId) : undefined;
  const confLines = [
    header(input.revisionId, "#"),
    ...layout.settings.filter((s) => s.firmware === "zmk").map(settingLine),
    ...layout.passthrough.filter((p) => p.file === CONF_FILE).map((p) => p.source),
    ...(marker?.shared ?? []),
  ];

  // KEYMAP_FILE and CONF_FILE label the layout's passthrough (they are stored in saved layouts); the
  // files written to disk are named for the board.
  const name = input.keymapName ?? "glove80";
  const gone = missingLayerNumbers(input.layout);
  if (gone.length > 0) throw new GenerateError(`kept firmware source names ${gone.map((id) => `layer "${id}"`).join(", ")} by number, and no layer has that id any more`);
  return {
    keymapName: name,
    files: [
      { path: `${name}.keymap`, content: `${keymapText.join("\n")}\n` },
      { path: `${name}.conf`, content: `${confLines.join("\n")}\n` },
      ...(marker?.perHalf ?? []),
    ],
  };
}
