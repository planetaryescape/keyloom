import { describe, expect, test } from "bun:test";
import { isDeepStrictEqual } from "node:util";
import { importOryxSource } from "../../../src/firmware/qmk/import.ts";
import { bindingToC } from "../../../src/firmware/qmk/emit-binding.ts";
import { GenerateError, generateQmkSource } from "../../../src/firmware/qmk/generate.ts";
import { writeSource } from "../../../src/firmware/qmk/write-source.ts";
import type { Binding, Combo, Layout, Macro } from "../../../src/layout/schema.ts";
import { FIXTURE_DIR, moonlander } from "../../helpers/board.ts";
import { tempDir } from "../../helpers/tmp.ts";

const board = await moonlander();
const imported = await importOryxSource(FIXTURE_DIR, board.definition);
const layout = imported.layout;
const gen = (l: Layout) => generateQmkSource({ layout: l, board: board.definition, revisionId: "rev_TEST" });
const file = (l: Layout, name: string) => gen(l).files.find((f) => f.path === name)?.content ?? "";

const ctx = {
  layerIndex: new Map([["layer-0", 0], ["layer-1", 1], ["layer-20", 20]]),
  macroNames: new Map([["m", "ST_MACRO_7"]]),
};
const c = (b: Binding) => bindingToC(b, ctx);

/** The layout with one base-layer binding replaced. */
function withKey(l: Layout, position: number, binding: Binding): Layout {
  return { ...l, layers: l.layers.map((layer, i) => (i === 0 ? { ...layer, bindings: layer.bindings.map((b, p) => (p === position ? binding : b)) } : layer)) };
}

describe("round trip through the generator (the fixture is BK's real Oryx export)", () => {
  test("import -> generate -> import gives the same layout, with no differences to excuse", async () => {
    const dir = tempDir();
    await writeSource(dir, gen(layout));
    const again = await importOryxSource(dir, board.definition);
    for (const key of Object.keys(layout) as Array<keyof Layout>) {
      // Compared field by field so a failure names the part that differs.
      expect({ key, value: again.layout[key] }).toEqual({ key, value: layout[key] });
    }
    expect(isDeepStrictEqual(again.layout, layout)).toBe(true);
    expect(again.report.warnings).toEqual([]);
  });

  test("the output is byte-identical on every run", () => {
    const a = gen(layout);
    const b = gen(structuredClone(layout));
    expect(b).toEqual(a);
    expect(a.files.map((f) => f.path)).toEqual(["keymap.c", "config.h", "rules.mk", "keymap.json"]);
  });

  test("keymap.c and config.h say where they came from; rules.mk and keymap.json are the passthrough as imported", () => {
    const g = gen(layout);
    const get = (n: string) => g.files.find((f) => f.path === n)?.content ?? "";
    expect(get("keymap.c").split("\n")[0]).toBe("// Generated by keyloom from rev_TEST — edit in keyloom, not here");
    expect(get("config.h").split("\n")[0]).toBe("// Generated by keyloom from rev_TEST — edit in keyloom, not here");
    expect(get("rules.mk")).toBe(layout.passthrough.find((p) => p.file === "rules.mk")?.source ?? "");
    expect(JSON.parse(get("keymap.json"))).toEqual({ modules: ["zsa/oryx", "zsa/defaults"] });
  });

  test("the generated config.h carries the settings, SERIAL_NUMBER and a derived COMBO_COUNT", () => {
    const h = file(layout, "config.h");
    expect(h).toContain("#define CHORDAL_HOLD\n");
    expect(h).toContain("#define RGB_MATRIX_STARTUP_SPD 60\n");
    expect(h).toContain('#define SERIAL_NUMBER "QxKPz/zLQ3Md"\n');
    expect(h).toContain("#define COMBO_COUNT 8\n");
  });

  test("changing one key changes exactly one line of keymap.c", () => {
    const before = file(layout, "keymap.c").split("\n");
    const after = file(withKey(layout, 4, { kind: "key", code: "Z" }), "keymap.c").split("\n");
    expect(after).toHaveLength(before.length);
    const changed = before.flatMap((line, i) => (line === after[i] ? [] : [i]));
    expect(changed).toHaveLength(1);
    expect(after[changed[0] as number]).toContain("KC_Z");
  });

  test("a changed key re-imports as that key and nothing else", async () => {
    // Position 31 is on the home row, which is what makes the importer give it the home-row profile.
    const edited = withKey(layout, 31, { kind: "holdTap", tap: { code: "R" }, hold: { mods: ["LSFT"] }, profileId: "home-row-mods" });
    const dir = tempDir();
    await writeSource(dir, gen(edited));
    const again = await importOryxSource(dir, board.definition);
    expect(again.layout.layers[0]?.bindings[31]).toEqual({ kind: "holdTap", tap: { code: "R" }, hold: { mods: ["LSFT"] }, profileId: "home-row-mods" });
    expect(again.layout.layers.slice(1)).toEqual(layout.layers.slice(1));
    expect(again.layout.layers[0]?.bindings.filter((_, p) => p !== 31)).toEqual(layout.layers[0]?.bindings.filter((_, p) => p !== 31));
  });
});

describe("bindings", () => {
  test("keys, shifted keys and nested modifier wrappers", () => {
    expect(c({ kind: "key", code: "A" })).toBe("KC_A");
    expect(c({ kind: "key", code: "N4", mods: ["LSFT", "LGUI"] })).toBe("LSFT(LGUI(KC_4))");
    expect(c({ kind: "key", code: "SPACE", mods: ["LGUI", "LCTL", "LALT", "LSFT"] })).toBe("LCTL(LSFT(LALT(LGUI(KC_SPACE))))");
    expect(c({ kind: "key", code: "B", mods: ["RCTL", "RSFT"] })).toBe("RCTL(RSFT(KC_B))");
  });

  test("modifier keys", () => {
    expect(c({ kind: "modifier", mods: ["LSFT"] })).toBe("KC_LEFT_SHIFT");
    expect(c({ kind: "modifier", mods: ["RGUI"] })).toBe("KC_RIGHT_GUI");
    expect(c({ kind: "modifier", mods: ["LCTL", "LSFT", "LALT", "LGUI"] })).toBe("KC_HYPR");
    expect(c({ kind: "modifier", mods: ["LCTL", "LSFT", "LALT"] })).toBe("KC_MEH");
    expect(c({ kind: "modifier", mods: ["LCTL", "LSFT"] })).toBe("LCTL(KC_LEFT_SHIFT)");
  });

  test("hold-taps", () => {
    const hold = (tap: string, h: Extract<Binding, { kind: "holdTap" }>["hold"]): Binding => ({ kind: "holdTap", tap: { code: tap }, hold: h, profileId: "p" });
    expect(c(hold("S", { mods: ["LALT"] }))).toBe("MT(MOD_LALT, KC_S)");
    expect(c(hold("S", { mods: ["LSFT", "LCTL"] }))).toBe("MT(MOD_LCTL | MOD_LSFT, KC_S)");
    expect(c(hold("G", { mods: ["LCTL", "LSFT", "LALT", "LGUI"] }))).toBe("ALL_T(KC_G)");
    expect(c(hold("QUOTE", { layerId: "layer-1" }))).toBe("LT(1, KC_QUOTE)");
  });

  test("layers, macros, transparent, none and native", () => {
    expect(c({ kind: "layer", action: "momentary", layerId: "layer-1" })).toBe("MO(1)");
    expect(c({ kind: "layer", action: "toggle", layerId: "layer-1" })).toBe("TG(1)");
    expect(c({ kind: "layer", action: "to", layerId: "layer-0" })).toBe("TO(0)");
    expect(c({ kind: "layer", action: "oneShot", layerId: "layer-1" })).toBe("OSL(1)");
    expect(c({ kind: "macro", macroId: "m" })).toBe("ST_MACRO_7");
    expect(c({ kind: "transparent" })).toBe("KC_TRANSPARENT");
    expect(c({ kind: "none" })).toBe("KC_NO");
    expect(c({ kind: "native", firmware: "qmk", source: "TD(DANCE_0)", label: "TD0" })).toBe("TD(DANCE_0)");
  });

  test("what QMK can't express is an error that names the problem, not firmware that behaves differently", () => {
    const err = (b: Binding) => {
      try {
        c(b);
      } catch (e) {
        expect(e).toBeInstanceOf(GenerateError);
        return (e as Error).message;
      }
      throw new Error("expected GenerateError");
    };
    expect(err({ kind: "key", code: "A", mods: ["LCTL", "RSFT"] })).toContain("mixes left and right");
    expect(err({ kind: "holdTap", tap: { code: "A", mods: ["LSFT"] }, hold: { mods: ["LALT"] }, profileId: "p" })).toContain("tap side can't carry modifiers");
    expect(err({ kind: "holdTap", tap: { code: "A" }, hold: { layerId: "layer-20" }, profileId: "p" })).toContain("layers 0-15");
    expect(err({ kind: "layer", action: "to", layerId: "nope" })).toContain('"nope" doesn\'t exist');
    expect(err({ kind: "key", code: "NOT_A_KEY" })).toContain("not a key code");
    expect(err({ kind: "native", firmware: "zmk", source: "&kp A", label: "A" })).toContain("zmk");
    expect(err({ kind: "macro", macroId: "missing" })).toContain("doesn't exist");
  });

  test("an error names the layer and position", () => {
    expect(() => gen(withKey(layout, 9, { kind: "key", code: "A", mods: ["LCTL", "RSFT"] }))).toThrow(/layer layer-0, position 9: .*mixes left and right/);
  });
});

describe("macros", () => {
  const macro = (id: string, name: string, steps: Macro["steps"]): Macro => ({ id, name, steps });
  const withMacro = (m: Macro, extra: Macro[] = []): Layout => ({
    ...withKey(layout, 4, { kind: "macro", macroId: m.id }),
    macros: [...layout.macros, ...extra, m],
  });

  test("a macro made in keyloom takes the first free ST_MACRO_n and is typed with SEND_STRING", () => {
    const l = withMacro(macro("paste-twice", "Paste twice", [{ op: "tap", code: "V", mods: ["LGUI"] }, { op: "waitMs", ms: 50 }, { op: "tap", code: "V", mods: ["LGUI"] }]));
    const keymapC = file(l, "keymap.c");
    expect(keymapC).toContain("  ST_MACRO_4,\n");
    expect(keymapC).toContain("    case ST_MACRO_4:\n    if (record->event.pressed) {\n      SEND_STRING(SS_LGUI(SS_TAP(X_V)) SS_DELAY(50) SS_LGUI(SS_TAP(X_V)));\n    }\n    break;");
    expect(keymapC).toMatch(/^\s+ST_MACRO_4,\s+KC_BACKSPACE|KC_ESCAPE,\s+KC_1/m);
  });

  test("a macro reads back with the same steps (id and name are the C name)", async () => {
    const m = macro("m1", "Mine", [{ op: "tap", code: "H", mods: ["LCTL", "LSFT"] }, { op: "tap", code: "ENTER" }, { op: "waitMs", ms: 10 }]);
    const dir = tempDir();
    await writeSource(dir, gen(withMacro(m)));
    const again = await importOryxSource(dir, board.definition);
    const back = again.layout.macros.find((x) => x.name === "ST_MACRO_4");
    expect(back?.steps).toEqual(m.steps);
    expect(again.layout.layers[0]?.bindings[4]).toEqual({ kind: "macro", macroId: back?.id as string });
  });

  test("press and release steps use SS_DOWN and SS_UP, modifiers around the key", () => {
    const l = withMacro(macro("hold", "Hold", [{ op: "press", code: "A", mods: ["LSFT"] }, { op: "release", code: "A", mods: ["LSFT"] }]));
    expect(file(l, "keymap.c")).toContain("SEND_STRING(SS_DOWN(X_LEFT_SHIFT) SS_DOWN(X_A) SS_UP(X_A) SS_UP(X_LEFT_SHIFT));");
  });

  test("a key SEND_STRING has no name for is refused", () => {
    expect(() => gen(withMacro(macro("mc", "Mc", [{ op: "tap", code: "MISSION_CONTROL" }])))).toThrow(/MISSION_CONTROL/);
  });

  test("an existing ST_MACRO_n name is kept, so passthrough code that names it still works", () => {
    const l = withMacro(macro("x", "ST_MACRO_2", [{ op: "tap", code: "X" }]));
    // ST_MACRO_2 is taken by the imported macro, so the new one moves to the first free number.
    expect(file(l, "keymap.c")).toContain("case ST_MACRO_4:");
  });
});

describe("combos", () => {
  const combo = (over: Partial<Combo>): Combo => ({ id: "c", name: "C", positions: [45, 46], layerIds: "all", output: { kind: "key", code: "ESCAPE" }, ...over });
  const withCombos = (combos: Combo[], l: Layout = layout): Layout => ({ ...l, combos });

  test("a combo on 'all' layers needs no callbacks; positions become the base layer's keycodes", () => {
    const keymapC = file(withCombos([combo({})]), "keymap.c");
    expect(keymapC).toContain("const uint16_t PROGMEM combo0[] = { KC_C, KC_V, COMBO_END};");
    expect(keymapC).toContain("COMBO(combo0, KC_ESCAPE),");
    expect(keymapC).not.toContain("combo_should_trigger");
    expect(file(withCombos([combo({})]), "config.h")).toContain("#define COMBO_COUNT 1\n");
  });

  test("layer-scoped combos and per-combo timeouts get their callbacks and config.h flags", () => {
    const l = withCombos([combo({}), combo({ id: "d", layerIds: ["layer-1", "layer-2"], timeoutMs: 25 })]);
    const keymapC = file(l, "keymap.c");
    expect(keymapC).toContain("case 1: return layer_state_is(1) || layer_state_is(2);");
    expect(keymapC).toContain("case 1: return 25;");
    const h = file(l, "config.h");
    expect(h).toContain("#define COMBO_SHOULD_TRIGGER\n");
    expect(h).toContain("#define COMBO_TERM_PER_COMBO\n");
  });

  test("a combo on a transparent key, or with a hold-tap output, is refused", () => {
    expect(() => gen(withCombos([combo({ positions: [45, 7] })]))).not.toThrow(); // position 7 is a native key
    const transparentBase = withKey(layout, 45, { kind: "transparent" });
    expect(() => gen(withCombos([combo({})], transparentBase))).toThrow(/transparent on the base layer/);
    expect(() => gen(withCombos([combo({ output: { kind: "holdTap", tap: { code: "A" }, hold: { mods: ["LALT"] }, profileId: "p" } })]))).toThrow(/hold-tap/);
  });

  test("COMBO_ENABLE follows the combos: added when missing, switched off when the last combo goes", () => {
    const noRules = { ...layout, passthrough: layout.passthrough.filter((p) => p.file !== "rules.mk") };
    expect(file(withCombos([combo({})], noRules), "rules.mk")).toBe("COMBO_ENABLE = yes\n");
    expect(file(withCombos([], noRules), "rules.mk")).toBe("");
    const none = file(withCombos([]), "rules.mk");
    expect(none.startsWith(layout.passthrough.find((p) => p.file === "rules.mk")?.source as string)).toBe(true);
    expect(none.trimEnd().endsWith("COMBO_ENABLE = no")).toBe(true);
    expect(file(withCombos([]), "keymap.c")).not.toContain("key_combos");
  });
});

describe("hold-tap profiles", () => {
  const profile = (options: Record<string, number | boolean>) => ({ ...layout, holdTapProfiles: layout.holdTapProfiles.map((p) => (p.id === "home-row-mods" ? { ...p, options: { ...p.options, ...options } } : p)) });

  test("profiles equal to the settings add nothing", () => {
    expect(file(layout, "keymap.c")).not.toContain("get_tapping_term");
    expect(file(layout, "config.h")).not.toContain("PER_KEY");
  });

  test("a different tapping term for the home row becomes get_tapping_term over exactly those keys", () => {
    const l = profile({ TAPPING_TERM: 175 });
    const keymapC = file(l, "keymap.c");
    expect(keymapC).toContain("uint16_t get_tapping_term(uint16_t keycode, keyrecord_t *record) {");
    expect(keymapC).toContain("case MT(MOD_LALT, KC_S): return 175;");
    expect(keymapC).toContain("case ALL_T(KC_G): return 175;");
    expect(keymapC).not.toContain("case MT(MOD_LCTL, KC_Z)"); // mod-tap profile, not home row
    expect(keymapC).toContain("default: return TAPPING_TERM;");
    expect(file(l, "config.h")).toContain("#define TAPPING_TERM_PER_KEY\n");
  });

  test("a boolean override returns the layout-wide value for every other key", () => {
    const l = profile({ PERMISSIVE_HOLD: false });
    const keymapC = file(l, "keymap.c");
    expect(keymapC).toContain("bool get_permissive_hold(uint16_t keycode, keyrecord_t *record) {");
    expect(keymapC).toContain("case MT(MOD_LALT, KC_S): return false;");
    expect(keymapC).toContain("default: return true;");
    expect(file(l, "config.h")).toContain("#define PERMISSIVE_HOLD_PER_KEY\n");
  });

  test("an option QMK can't set per key is an error", () => {
    expect(() => gen(profile({ FLOW_TAP_TERM: 40 }))).toThrow(/can't set FLOW_TAP_TERM per key/);
  });

  test("a keymap.c that already defines the callback is not silently doubled", () => {
    const l = profile({ TAPPING_TERM: 175 });
    const dup = { ...l, passthrough: [...l.passthrough, { firmware: "qmk" as const, file: "keymap.c", anchor: "function:get_tapping_term", source: "uint16_t get_tapping_term(uint16_t k, keyrecord_t *r) { return 1; }", refersToLayerIndices: false }] };
    expect(() => gen(dup)).toThrow(/already defines get_tapping_term/);
  });
});

describe("layers and settings", () => {
  test("more layers than LAYER_STATE_8BIT allows is an error, because the extra layers would never turn on", () => {
    const extra = Array.from({ length: 3 }, (_, i) => ({ ...(layout.layers[0] as Layout["layers"][number]), id: `extra-${i}`, name: `Extra ${i}` }));
    expect(() => gen({ ...layout, layers: [...layout.layers, ...extra] })).toThrow(/LAYER_STATE_8BIT limits the layout to 8 layers/);
  });

  test("a layer with the wrong number of keys is an error", () => {
    const short = { ...layout, combos: [], layers: [{ ...(layout.layers[0] as Layout["layers"][number]), bindings: [] }, ...layout.layers.slice(1)] };
    expect(() => gen(short)).toThrow(/has 0 bindings, but zsa\/moonlander has 72 keys/);
  });

  test("setting values: numbers and flags, quoted strings as written, and an off flag is not defined", () => {
    const l = { ...layout, settings: [
      ...layout.settings,
      { firmware: "qmk" as const, key: "A_NUM", value: 7 },
      { firmware: "qmk" as const, key: "A_FLAG", value: true },
      { firmware: "qmk" as const, key: "AN_OFF_FLAG", value: false },
      { firmware: "qmk" as const, key: "PRODUCT", value: '"My board"' },
      { firmware: "zmk" as const, key: "NOT_FOR_QMK", value: 1 },
    ] };
    const h = file(l, "config.h");
    expect(h).toContain("#define A_NUM 7\n#define A_FLAG\n// AN_OFF_FLAG is off, so it is not defined\n#define PRODUCT \"My board\"\n");
    expect(h).not.toContain("NOT_FOR_QMK");
  });

  test("layer names can't break out of their comment", () => {
    const named = { ...layout, layers: layout.layers.map((l, i) => (i === 0 ? { ...l, name: "Base\\\nint evil;" } : l)) };
    expect(file(named, "keymap.c")).toContain("// layer-0: Base/ int evil;\n");
  });
});
