import { describe, expect, test } from "bun:test";
import fc from "fast-check";
import { KEYCODES } from "../../../src/layout/keycodes.ts";
import type { Binding, Layout, Mod } from "../../../src/layout/schema.ts";
import { GenerateError, generateZmkSource } from "../../../src/firmware/zmk/generate.ts";
import { importZmk, importZmkSource } from "../../../src/firmware/zmk/import.ts";
import { STYLE_FIXTURE, TEMPLATE_FIXTURE, glove80 } from "../../helpers/zmk.ts";

const board = await glove80();
const def = board.definition;

const gen = (layout: Layout, revisionId = "rev_T") => generateZmkSource({ layout, board: def, geometry: board.geometry, revisionId });
const files = (layout: Layout) => Object.fromEntries(gen(layout).files.map((f) => [f.path, f.content])) as Record<string, string>;
const reimport = async (layout: Layout) => {
  const f = files(layout);
  return (await importZmk({ name: "x", keymap: f["glove80.keymap"] as string, conf: f["glove80.conf"] as string }, def)).layout;
};

describe.each([
  ["the template's default keymap", TEMPLATE_FIXTURE],
  ["a Layout Editor style keymap", STYLE_FIXTURE],
])("round trip: %s", (_name, dir) => {
  test("import, generate, import gives an identical layout (rung 5's completion check)", async () => {
    const first = await importZmkSource(dir, def);
    expect(await reimport(first.layout)).toEqual(first.layout);
  });

  test("generating the second import gives the same bytes, so output is deterministic", async () => {
    const first = await importZmkSource(dir, def);
    const again = await reimport(first.layout);
    expect(files(again)).toEqual(files(first.layout));
  });
});

describe("the generated files", () => {
  test("keymap: header, includes, defines, behaviors, macros, combos, then the keymap node", async () => {
    const { layout } = await importZmkSource(STYLE_FIXTURE, def);
    const text = files(layout)["glove80.keymap"] as string;
    expect(text.startsWith("// Generated by keyloom from rev_T — edit in keyloom, not here\n\n#include <behaviors.dtsi>")).toBe(true);
    const order = ["#include <dt-bindings/zmk/pointing.h>", "#define HYPER", "/ {", "    behaviors {", "    macros {", "    combos {", "    keymap {", "\n&mt {", "\n&sk {"].map((s) => text.indexOf(s));
    expect(order.every((n) => n >= 0)).toBe(true);
    expect([...order].sort((a, b) => a - b)).toEqual(order);
  });

  test("a hold-tap profile is written with ZMK's property names and the built-in &mt only as an override", async () => {
    const { layout } = await importZmkSource(STYLE_FIXTURE, def);
    const text = files(layout)["glove80.keymap"] as string;
    expect(text).toContain('hm: hm {\n            compatible = "zmk,behavior-hold-tap";\n            display-name = "HOMEROW_MODS";\n            #binding-cells = <2>;\n            bindings = <&kp>, <&kp>;\n            flavor = "balanced";\n            tapping-term-ms = <280>;');
    expect(text).toContain("hold-trigger-on-release;");
    expect(text).toContain("&mt {\n    tapping-term-ms = <175>;\n};");
    expect(text).not.toContain("mt: ");
  });

  test("bindings sit in the keyboard's six rows with the hands apart", async () => {
    const { layout } = await importZmkSource(TEMPLATE_FIXTURE, def);
    const text = files(layout)["glove80.keymap"] as string;
    const block = text.split("bindings = <\n")[1]?.split("\n            >;")[0] ?? "";
    const rows = block.split("\n");
    expect(rows).toHaveLength(6);
    expect(rows.map((r) => r.match(/&/g)?.length)).toEqual([10, 12, 12, 12, 18, 16]);
    expect(rows[0]).toMatch(/&kp F5 +&kp F6/);
  });

  test("the conf holds the settings, then the lines keyloom couldn't read", async () => {
    const { layout } = await importZmkSource(STYLE_FIXTURE, def);
    expect(files(layout)["glove80.conf"]).toBe(
      "# Generated by keyloom from rev_T — edit in keyloom, not here\nCONFIG_ZMK_SLEEP=y\nCONFIG_ZMK_IDLE_SLEEP_TIMEOUT=900000\nCONFIG_BT_CTLR_TX_PWR_PLUS_8=y\nCONFIG_ZMK_PM_SOFT_OFF=n\nCONFIG_ZMK_KEYBOARD_NAME=\"Glove80 Test\"\n",
    );
    const odd = await importZmk({ name: "x", keymap: files((await importZmkSource(TEMPLATE_FIXTURE, def)).layout)["glove80.keymap"] as string, conf: "CONFIG_A=y\nsome odd line\n" }, def);
    expect(files(odd.layout)["glove80.conf"]).toContain("CONFIG_A=y\nsome odd line\n");
  });
});

describe("editing the layout and writing it again", () => {
  test("a changed key, a new macro and a new hold-tap profile come back as what was written", async () => {
    const { layout } = await importZmkSource(TEMPLATE_FIXTURE, def);
    const edited: Layout = {
      ...layout,
      layers: layout.layers.map((l, i) =>
        i !== 0 ? l : {
          ...l,
          bindings: l.bindings.map((b, p): Binding =>
            p === 35 ? { kind: "holdTap", tap: { code: "A" }, hold: { mods: ["LGUI"] }, profileId: "home-row-mods" }
            : p === 36 ? { kind: "macro", macroId: "opt-opt" }
            : p === 37 ? { kind: "layer", action: "momentary", layerId: "lower-layer" }
            : p === 38 ? { kind: "key", code: "N1", mods: ["LSFT", "LCTL"] }
            : b),
        },
      ),
      macros: [{ id: "opt-opt", name: "Option twice", steps: [{ op: "tap", mods: ["LALT"] }, { op: "waitMs", ms: 30 }, { op: "press", mods: ["LALT"] }, { op: "release", mods: ["LALT"] }] }],
      holdTapProfiles: [{ id: "home-row-mods", name: "Home row mods", firmware: "zmk", options: { flavor: "balanced", "tapping-term-ms": 250, "hold-trigger-key-positions": [5, 6], "retro-tap": true } }],
    };
    const text = files(edited)["glove80.keymap"] as string;
    expect(text).toContain("home_row_mods: home_row_mods {");
    expect(text).toContain("&home_row_mods LGUI A");
    expect(text).toContain("&opt_opt");
    expect(text).toContain("&mo 1");
    expect(text).toContain("&kp LC(LS(N1))");
    expect(text).toContain("<&kp LALT>,\n");
    expect(text).toContain("<&macro_wait_time 30>");
    expect(text).toContain("<&macro_press &kp LALT>");
    const back = await reimport(edited);
    expect(back.layers[0]?.bindings.slice(35, 39)).toEqual([
      { kind: "holdTap", tap: { code: "A" }, hold: { mods: ["LGUI"] }, profileId: "home_row_mods" },
      { kind: "macro", macroId: "opt_opt" },
      { kind: "layer", action: "momentary", layerId: "lower-layer" },
      { kind: "key", code: "N1", mods: ["LCTL", "LSFT"] },
    ]);
    expect(back.holdTapProfiles[0]).toEqual({ id: "home_row_mods", name: "Home row mods", firmware: "zmk", options: { bindings: "&kp &kp", flavor: "balanced", "tapping-term-ms": 250, "hold-trigger-key-positions": [5, 6], "retro-tap": true } });
    expect(back.macros[0]?.steps).toEqual(edited.macros[0]?.steps);
  });

  test("a profile whose holds are layers is written as &mo/&kp when it names no bindings", async () => {
    const { layout } = await importZmkSource(TEMPLATE_FIXTURE, def);
    const edited: Layout = {
      ...layout,
      layers: layout.layers.map((l, i) => (i === 0 ? { ...l, bindings: l.bindings.map((b, p): Binding => (p === 0 ? { kind: "holdTap", tap: { code: "SPACE" }, hold: { layerId: "lower-layer" }, profileId: "nav" } : b)) } : l)),
      holdTapProfiles: [{ id: "nav", name: "Nav", firmware: "zmk", options: {} }],
    };
    expect(files(edited)["glove80.keymap"]).toContain("bindings = <&mo>, <&kp>;");
  });

  test("a changed built-in is written as an override and a default one is not written at all", async () => {
    const { layout } = await importZmkSource(STYLE_FIXTURE, def);
    const lt = layout.holdTapProfiles.find((p) => p.id === "lt");
    expect(files(layout)["glove80.keymap"]).not.toContain("&lt {");
    const tuned: Layout = { ...layout, holdTapProfiles: layout.holdTapProfiles.map((p) => (p === lt ? { ...p, options: { ...p.options, "tapping-term-ms": 150, "quick-tap-ms": 100 } } : p)) };
    expect(files(tuned)["glove80.keymap"]).toContain("&lt {\n    tapping-term-ms = <150>;\n    quick-tap-ms = <100>;\n};");
    expect((await reimport(tuned)).holdTapProfiles.find((p) => p.id === "lt")?.options).toMatchObject({ "tapping-term-ms": 150, "quick-tap-ms": 100 });
  });

  test("a combo on every layer is written without layers, because <(-1)> does not compile on this firmware", async () => {
    const { layout } = await importZmkSource(STYLE_FIXTURE, def);
    const text = files(layout)["glove80.keymap"] as string;
    expect(text).toContain("combo_esc {\n            timeout-ms = <40>;\n            key-positions = <12 13>;\n            bindings = <&kp ESC>;");
    expect(text).not.toContain("(-1)");
  });

  test("a new combo is written with its layers as numbers and its timeout", async () => {
    const { layout } = await importZmkSource(TEMPLATE_FIXTURE, def);
    const edited: Layout = { ...layout, combos: [{ id: "x", name: "Esc combo", positions: [12, 13], layerIds: ["default-layer", "lower-layer"], output: { kind: "key", code: "ESCAPE" }, timeoutMs: 30 }] };
    expect(files(edited)["glove80.keymap"]).toContain("Esc_combo {\n            timeout-ms = <30>;\n            key-positions = <12 13>;\n            layers = <0 1>;\n            bindings = <&kp ESC>;\n        };");
    expect((await reimport(edited)).combos[0]).toMatchObject({ positions: [12, 13], layerIds: ["default-layer", "lower-layer"], timeoutMs: 30 });
  });
});

describe("what it refuses to write", () => {
  const base = async () => (await importZmkSource(TEMPLATE_FIXTURE, def)).layout;

  test("a binding that refers to a layer, macro or profile that doesn't exist names the layer and position", async () => {
    const l = await base();
    const bad = (b: Binding): Layout => ({ ...l, layers: l.layers.map((x, i) => (i === 1 ? { ...x, bindings: x.bindings.map((y, p) => (p === 3 ? b : y)) } : x)) });
    expect(() => gen(bad({ kind: "layer", action: "to", layerId: "nope" }))).toThrow('layer lower-layer, position 3: it refers to layer "nope", which doesn\'t exist');
    expect(() => gen(bad({ kind: "macro", macroId: "nope" }))).toThrow(/macro "nope"/);
    expect(() => gen(bad({ kind: "holdTap", tap: { code: "A" }, hold: { mods: ["LGUI"] }, profileId: "nope" }))).toThrow(/profile "nope"/);
    expect(() => gen(bad({ kind: "key", code: "NOT_A_KEY" }))).toThrow(GenerateError);
    expect(() => gen(bad({ kind: "native", firmware: "qmk", source: "KC_A", label: "A" }))).toThrow(/qmk binding/);
  });

  test("a wrong number of keys, duplicate layer ids, too many layers and a QMK layout are refused", async () => {
    const l = await base();
    expect(() => gen({ ...l, layers: [{ ...l.layers[0]!, bindings: l.layers[0]!.bindings.slice(1) }] })).toThrow(/has 79 bindings, but moergo\/glove80 has 80/);
    expect(() => gen({ ...l, layers: [l.layers[0]!, l.layers[0]!] })).toThrow(/two layers are called/);
    expect(() => gen({ ...l, layers: Array.from({ length: 33 }, (_, i) => ({ ...l.layers[0]!, id: `l${i}` })) })).toThrow(/at most 32/);
    expect(() => gen({ ...l, firmware: "qmk" })).toThrow(/not a ZMK board/);
    expect(() => gen({ ...l, boardId: "zsa/moonlander" })).toThrow(/is for zsa\/moonlander/);
  });

  test("an id that would be written as one of ZMK's behaviours, or twice, is refused", async () => {
    const l = await base();
    const profile = (id: string) => ({ id, name: id, firmware: "zmk" as const, options: {} });
    expect(() => gen({ ...l, holdTapProfiles: [profile("kp")] })).toThrow(/&kp, which is a ZMK behaviour/);
    expect(() => gen({ ...l, holdTapProfiles: [profile("a-b"), profile("a_b")] })).toThrow(/both be written as a_b/);
  });

  test("a combo that outputs a hold-tap, and passthrough for a file keyloom doesn't write, are refused", async () => {
    const l = await base();
    expect(() => gen({ ...l, holdTapProfiles: [{ id: "hm", name: "hm", firmware: "zmk", options: {} }], combos: [{ id: "c", name: "c", positions: [1, 2], layerIds: "all", output: { kind: "holdTap", tap: { code: "A" }, hold: { mods: ["LGUI"] }, profileId: "hm" } }] })).toThrow(/outputs a hold-tap/);
    expect(() => gen({ ...l, passthrough: [{ firmware: "zmk", file: "west.yml", anchor: "file", source: "x", refersToLayerIndices: false }] })).toThrow(/only writes glove80\.keymap and glove80\.conf/);
    expect(() => gen({ ...l, passthrough: [{ firmware: "zmk", file: "glove80.keymap", anchor: "mystery:1", source: "x", refersToLayerIndices: false }] })).toThrow(/doesn't know where to write/);
  });
});

describe("property: any bindings the model holds survive a write and a read", () => {
  const mods = fc.subarray(["LCTL", "LSFT", "LALT", "LGUI", "RCTL", "RSFT", "RALT", "RGUI"] as Mod[], { minLength: 1 });
  const code = fc.constantFrom(...KEYCODES.filter((k) => k.zmk.length > 0 && k.category !== "modifier").map((k) => k.name));
  const binding: fc.Arbitrary<Binding> = fc.oneof(
    fc.record({ kind: fc.constant("key" as const), code }),
    fc.record({ kind: fc.constant("key" as const), code, mods }),
    fc.record({ kind: fc.constant("modifier" as const), mods }),
    fc.record({ kind: fc.constant("holdTap" as const), tap: fc.record({ code }), hold: fc.record({ mods }), profileId: fc.constant("hm") }),
    fc.record({ kind: fc.constant("holdTap" as const), tap: fc.record({ code, mods }), hold: fc.record({ layerId: fc.constant("lower-layer") }), profileId: fc.constant("lt") }),
    fc.record({ kind: fc.constant("layer" as const), action: fc.constantFrom("momentary", "toggle", "to", "oneShot" as const), layerId: fc.constantFrom("default-layer", "lower-layer") }),
    fc.constant({ kind: "transparent" as const }),
    fc.constant({ kind: "none" as const }),
  );

  test("100 random layers", async () => {
    const { layout } = await importZmkSource(TEMPLATE_FIXTURE, def);
    const withProfiles: Layout = {
      ...layout,
      holdTapProfiles: [
        { id: "hm", name: "hm", firmware: "zmk", options: { bindings: "&kp &kp", flavor: "balanced", "tapping-term-ms": 200 } },
        { id: "lt", name: "Layer-Tap", firmware: "zmk", options: { bindings: "&mo &kp", flavor: "tap-preferred", "tapping-term-ms": 200 } },
      ],
    };
    await fc.assert(
      fc.asyncProperty(fc.array(binding, { minLength: 80, maxLength: 80 }), async (bindings) => {
        const l: Layout = { ...withProfiles, layers: withProfiles.layers.map((x, i) => (i === 1 ? { ...x, bindings } : x)) };
        const back = await reimport(l);
        // A key whose code is a modifier key reads back as a `modifier`; the table's non-modifier keys avoid that.
        expect(back.layers[1]?.bindings).toEqual(bindings);
      }),
      { numRuns: 100 },
    );
  });
});
