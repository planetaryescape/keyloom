async function until<T>(fn: () => Promise<T>, done: (v: T) => boolean, ms = 10_000): Promise<T> {
  const end = Date.now() + ms;
  for (;;) {
    const v = await fn();
    if (done(v) || Date.now() > end) return v;
    await Bun.sleep(25);
  }
}

describe("generateFirmware", () => {
  test("writes the four files for a layout revision", async () => {
    const e = await toolchainEnv();
    const out = join(e.root, "gen");
    const r = await generateFirmware(e.app, "synchronized", { out });
    expect(r.files).toEqual(["keymap.c", "config.h", "rules.mk", "keymap.json"]);
    expect(r.dir).toBe(out);
    expect(await Bun.file(join(out, "keymap.c")).text()).toContain(`Generated by keyloom from ${e.imported.revisionId}`);
  });

  test("leaves other files in --out alone", async () => {
    const e = await toolchainEnv();
    const out = join(e.root, "gen");
    await Bun.write(join(out, "mine.txt"), "keep");
    await generateFirmware(e.app, "synchronized", { out });
    expect(await Bun.file(join(out, "mine.txt")).text()).toBe("keep");
  });

  test("a layout QMK can't express is a validation failure that names the key", async () => {
    const e = await toolchainEnv();
    const db = e.app.db;
    const row = db.query("SELECT id, document FROM revisions").get() as { id: string; document: string };
    const doc = JSON.parse(row.document);
    doc.layers[0].bindings[5] = { kind: "key", code: "A", mods: ["LCTL", "RSFT"] };
    db.query("UPDATE revisions SET document = ? WHERE id = ?").run(JSON.stringify(doc), row.id);
    await expect(generateFirmware(e.app, "synchronized", { out: join(e.root, "x") })).rejects.toThrow(ValidationFailedError);
    await expect(generateFirmware(e.app, "synchronized", { out: join(e.root, "x") })).rejects.toThrow(/layer layer-0, position 5/);
  });

  test("an unknown layout or revision is not found", async () => {
    const e = await toolchainEnv();
    await expect(generateFirmware(e.app, "nope", { out: join(e.root, "x") })).rejects.toThrow(NotFoundError);
    await expect(generateFirmware(e.app, "synchronized", { out: join(e.root, "x"), rev: "rev_nope" })).rejects.toThrow(NotFoundError);
  });
});

describe("startBuild / getBuild / buildAndWait", () => {
  test("startBuild returns a running build at once; polling shows it succeed with the artifact under the data dir", async () => {
    const e = await toolchainEnv();
    await e.run(async () => {
      const started = await startBuild(e.app, "synchronized", { boardRevision: "revb" });
      expect(started).toMatchObject({ status: "running", artifactPath: null, finishedAt: null, boardRevision: "revb", revisionId: e.imported.revisionId });
      expect(started.id).toMatch(/^bld_[0-9A-Z]{26}$/);
      const done = await until(() => getBuild(e.app, started.id), (b) => b.status !== "running");
      expect(done.status).toBe("succeeded");
      expect(done.error).toBeNull();
      expect(done.artifactPath).toBe(join(e.dataDir, "artifacts", `${started.id}.bin`));
      expect(Buffer.from(await Bun.file(done.artifactPath as string).bytes()).equals(REVB)).toBe(true);
      expect(done.logTail.join("\n")).toContain("DFU 3297:2003");
      expect(done.logTail.length).toBeLessThanOrEqual(30);
      // The shape the server returns, as src/api/http.ts defines it.
      expect(() => BuildSchema.parse(done)).not.toThrow();
    });
  });

  test("buildAndWait streams progress and returns the finished build", async () => {
    const e = await toolchainEnv();
    await e.run(async () => {
      const lines: string[] = [];
      const b = await buildAndWait(e.app, "synchronized", { boardRevision: "revb", onProgress: (l) => lines.push(l) });
      expect(b.status).toBe("succeeded");
      expect(lines.some((l) => l.includes("Compiling"))).toBe(true);
    });
  });

  test("the revision to build can be an earlier one", async () => {
    const e = await toolchainEnv();
    await e.run(async () => {
      const b = await buildAndWait(e.app, "synchronized", { boardRevision: "reva", revisionId: e.imported.revisionId });
      expect(b.boardRevision).toBe("reva");
      expect(Buffer.from(await Bun.file(b.artifactPath as string).bytes()).equals(REVA)).toBe(true);
    });
  });

  test("with two board revisions and no keyboard to ask, the build says to pass --board-rev", async () => {
    const e = await toolchainEnv();
    await e.run(async () => {
      await expect(startBuild(e.app, "synchronized")).rejects.toThrow(UsageError);
      await expect(startBuild(e.app, "synchronized")).rejects.toThrow(/--board-rev reva\|revb/);
      await expect(startBuild(e.app, "synchronized", { boardRevision: "revc" })).rejects.toThrow(/no revision "revc"/);
    });
  });

  test("a connected Moonlander is recognised by its USB product ID", async () => {
    const e = await toolchainEnv();
    const usb = (pid: string, maker = "ZSA Technology Labs") => JSON.stringify({ SPUSBDataType: [{ _items: [{ _name: "Moonlander Mark I", product_id: pid, vendor_id: "0x3297", manufacturer: maker }] }] });
    await e.run(async () => {
      expect((await buildAndWait(e.app, "synchronized")).boardRevision).toBe("revb");
    }, { FAKE_USB: usb("0x1972") });
    await e.run(async () => {
      expect((await buildAndWait(e.app, "synchronized")).boardRevision).toBe("reva");
    }, { FAKE_USB: usb("0x1969") });
    // Someone else's device with the same product ID is not a Moonlander.
    await e.run(async () => {
      await expect(startBuild(e.app, "synchronized")).rejects.toThrow(/--board-rev/);
    }, { FAKE_USB: usb("0x1972", "Acme Widgets") });
  });

  test("a compile error fails the build with a message, keeps the log, and buildAndWait throws BuildFailedError", async () => {
    const e = await toolchainEnv();
    await e.run(async () => {
      const err = await buildAndWait(e.app, "synchronized", { boardRevision: "revb" }).catch((x) => x as BuildFailedError);
      expect(err).toBeInstanceOf(BuildFailedError);
      expect((err as BuildFailedError).message).toContain("doesn't compile");
      const b = await getBuild(e.app, (err as BuildFailedError).buildId);
      expect(b).toMatchObject({ status: "failed", artifactPath: null });
      expect(b.finishedAt).not.toBeNull();
      expect(b.logTail.join("\n")).toContain("build failed");
      expect(() => BuildSchema.parse(b)).not.toThrow();
    }, { FAKE_MODE: "compile", FAKE_LINE: "40", FAKE_COL: "3" });
  });

  test("Docker not running fails the build before anything is cloned or generated", async () => {
    const e = await toolchainEnv();
    await e.run(async () => {
      const err = (await buildAndWait(e.app, "synchronized", { boardRevision: "revb" }).catch((x) => x)) as BuildFailedError;
      expect(err.message).toContain("daemon isn't running");
    }, { FAKE_MODE: "nodaemon" });
    expect(await Bun.file(e.vars.FAKE_DOCKER_LOG).exists()).toBe(false);
  });

  test("a build row whose process died is reported as failed, not running forever", async () => {
    const e = await toolchainEnv();
    const id = newBuildId();
    createBuild(e.app.db, { id, revisionId: e.imported.revisionId, layoutId: e.imported.layoutId, boardRevision: "revb", logPath: `logs/build-${id}.log`, pid: 2147483646 });
    const b = await getBuild(e.app, id);
    expect(b.status).toBe("failed");
    expect(b.error).toContain("stopped before this build finished");
  });

  test("an unknown build is not found", async () => {
    const e = await toolchainEnv();
    await expect(getBuild(e.app, "bld_nope")).rejects.toThrow(NotFoundError);
  });
});

describe("startFlash / flashAndWait (fake zapp)", () => {
  async function built(e: Awaited<ReturnType<typeof toolchainEnv>>, rev = "revb") {
    return e.run(() => buildAndWait(e.app, "synchronized", { boardRevision: rev }));
  }

  test("flashes the newest successful build of a layout, reporting the instruction and then the result", async () => {
    const e = await toolchainEnv();
    const b = await built(e);
    await e.run(async () => {
      const seen: Array<[string, string | null]> = [];
      const f = await flashAndWait(e.app, { layout: "synchronized", onState: (s) => seen.push([s.status, s.instruction]) });
      expect(f).toMatchObject({ status: "succeeded", error: null, buildId: b.id, instruction: null });
      expect(f.id).toMatch(/^fl_[0-9A-Z]{26}$/);
      expect(seen[0]?.[0]).toBe("waiting_for_bootloader");
      // The flasher first checks whether the keyboard can be restarted by keyloom; with none attached it asks for the key.
      expect(seen[0]?.[1]).toContain("checking whether it can restart the keyboard");
      expect(seen.some(([, i]) => i?.includes("Press the reset button on the Moonlander"))).toBe(true);
      expect(seen.map(([s]) => s)).toContain("writing");
      expect(seen.at(-1)?.[0]).toBe("succeeded");
      expect(() => FlashSchema.parse(f)).not.toThrow();
      expect(await Bun.file(e.vars.ZAPP_CALLS).text()).toBe("ran\n");
    });
  });

  test("startFlash returns at once, waiting for the bootloader, and getFlash follows it", async () => {
    const e = await toolchainEnv();
    await built(e);
    await e.run(async () => {
      const f = await startFlash(e.app, { layout: "synchronized" });
      expect(f.status).toBe("waiting_for_bootloader");
      expect(f.instruction).toContain("checking whether it can restart the keyboard");
      const done = await until(() => getFlash(e.app, f.id), (x) => x.status === "succeeded" || x.status === "failed");
      expect(done.status).toBe("succeeded");
    });
  });

  test("manual flash draining waits for the flash before closing the helper", async () => {
    const e = await toolchainEnv();
    await built(e);
    const flashFinished = Promise.withResolvers<void>();
    const allowFlashTaskToFinish = Promise.withResolvers<void>();
    await e.run(async () => {
      await startFlash(e.app, {
        layout: "synchronized",
        onState: async (flash) => {
          if (flash.status === "succeeded") {
            flashFinished.resolve();
            await allowFlashTaskToFinish.promise;
          }
        },
      });
      await flashFinished.promise;
      let helperClosed = false;
      const draining = drainDeviceConsumers([drainManualFlashTasks()], async () => { helperClosed = true; });
      await Bun.sleep(10);
      expect(helperClosed).toBe(false);
      allowFlashTaskToFinish.resolve();
      await draining;
      expect(helperClosed).toBe(true);
    });
  });

  test("an explicit build wins over the newest one, so a known-good build can be restored", async () => {
    const e = await toolchainEnv();
    const first = await built(e);
    await built(e);
    await e.run(async () => {
      const f = await flashAndWait(e.app, { buildId: first.id });
      expect(f.buildId).toBe(first.id);
    });
  });

  test("a failed build, an unknown build, and a layout with no build are refused before zapp runs", async () => {
    const e = await toolchainEnv();
    const failed = await e.run(() => buildAndWait(e.app, "synchronized", { boardRevision: "revb" }).catch((x) => x as BuildFailedError), { FAKE_MODE: "disk" });
    await e.run(async () => {
      await expect(startFlash(e.app, { buildId: (failed as BuildFailedError).buildId })).rejects.toThrow(/only a successful build can be flashed/);
      await expect(startFlash(e.app, { buildId: "bld_nope" })).rejects.toThrow(NotFoundError);
      await expect(startFlash(e.app, { layout: "synchronized" })).rejects.toThrow(/no successful build/);
      await expect(startFlash(e.app, { layout: "nope" })).rejects.toThrow(NotFoundError);
    });
    expect(await Bun.file(e.vars.ZAPP_CALLS).exists()).toBe(false);
  });

  test("with one layout saved, neither flag is needed; with none to choose, it asks", async () => {
    const e = await toolchainEnv();
    await built(e);
    await e.run(async () => {
      expect((await flashAndWait(e.app, {})).status).toBe("succeeded");
    });
    await importLayout(e.app, { board: "zsa/moonlander", source: FIXTURE_DIR, name: "second" });
    await e.run(async () => {
      await expect(startFlash(e.app, {})).rejects.toThrow(/say what to flash/);
    });
  });

  test("no keyboard in bootloader mode: the flash fails after the wait, with nothing flashed (fake zapp, short wait)", async () => {
    const e = await toolchainEnv({ zapp: FAKE_ZAPP_HANG });
    await built(e);
    await e.run(async () => {
      const err = (await flashAndWait(e.app, { layout: "synchronized", bootloaderWaitMs: 400 }).catch((x) => x)) as FlashFailedError;
      expect(err).toBeInstanceOf(FlashFailedError);
      expect(err.message).toContain("No Moonlander in bootloader mode was found");
      const f = await getFlash(e.app, err.flashId);
      expect(f).toMatchObject({ status: "failed", instruction: null });
    });
  });

  test("aborting a flash cancels it and leaves nothing waiting", async () => {
    const e = await toolchainEnv({ zapp: FAKE_ZAPP_HANG });
    await built(e);
    await e.run(async () => {
      const c = new AbortController();
      setTimeout(() => c.abort(), 300);
      const err = (await flashAndWait(e.app, { layout: "synchronized", signal: c.signal }).catch((x) => x)) as FlashFailedError;
      expect(err.message).toContain("Cancelled. Nothing was flashed.");
    });
  });

  test("only one flash at a time", async () => {
    const e = await toolchainEnv({ zapp: FAKE_ZAPP_HANG });
    await built(e);
    await e.run(async () => {
      const first = await startFlash(e.app, { layout: "synchronized", bootloaderWaitMs: 700 });
      await expect(startFlash(e.app, { layout: "synchronized" })).rejects.toThrow(new RegExp(`flash ${first.id} is already in progress`));
      await until(() => getFlash(e.app, first.id), (x) => x.status === "failed");
      // Once the first has ended, a new one is allowed.
      const next = await startFlash(e.app, { layout: "synchronized", bootloaderWaitMs: 300 });
      await until(() => getFlash(e.app, next.id), (x) => x.status === "failed");
    });
  });

  test("a binary for the other revision is never handed to zapp", async () => {
    const e = await toolchainEnv();
    const b = await built(e);
    await Bun.write(b.artifactPath as string, REVA); // as if the wrong file had ended up under this build
    await e.run(async () => {
      const err = (await flashAndWait(e.app, { buildId: b.id }).catch((x) => x)) as FlashFailedError;
      expect(err.message).toContain("Not flashing");
    });
    expect(await Bun.file(e.vars.ZAPP_CALLS).exists()).toBe(false);
  });

  test("a flash whose process died is reported as failed", async () => {
    const e = await toolchainEnv();
    const b = await built(e);
    const db: Database = e.app.db;
    db.query("INSERT INTO flashes (id, build_id, status, log_path, pid, started_at) VALUES ('fl_dead', ?, 'writing', 'logs/x.log', 2147483646, 1)").run(b.id);
    const f = await getFlash(e.app, "fl_dead");
    expect(f.status).toBe("failed");
    expect(f.error).toContain("stopped before this flash finished");
  });
});

