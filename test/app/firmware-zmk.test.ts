async function until<T>(fn: () => Promise<T>, done: (v: T) => boolean, ms = 10_000): Promise<T> {
  const end = Date.now() + ms;
  for (;;) {
    const v = await fn();
    if (done(v) || Date.now() > end) return v;
    await Bun.sleep(25);
  }
}

const RIGHT = "GLV80RHBOOT";
const LEFT = "GLV80LHBOOT";

describe("import and generate", () => {
  test("a Glove80 layout is imported from the template's keymap with the same use case the Moonlander uses", async () => {
    const e = await zmkEnv();
    const view = getLayout(e.app, e.imported.layoutId);
    expect(view.document.firmware).toBe("zmk");
    expect(view.document.layers).toHaveLength(4);
    expect(view.board.definition.id).toBe("moergo/glove80");
    expect(e.imported.name).toBe("glove80");
    expect(e.imported.report).toMatchObject({ layers: 4, keysPerLayer: 80 });
  });

  test("generate writes glove80.keymap and glove80.conf", async () => {
    const e = await zmkEnv();
    const out = join(e.root, "gen");
    const r = await generateFirmware(e.app, "glove80", { out });
    expect(r.files).toEqual(["glove80.keymap", "glove80.conf"]);
    expect(await Bun.file(join(out, "glove80.keymap")).text()).toContain(`Generated by keyloom from ${e.imported.revisionId}`);
  });

  test("a layout the board's importer can't read is a usage error that names the problem", async () => {
    const e = await zmkEnv();
    const { importLayout } = await import("../../src/app/index.ts");
    await Bun.write(join(e.root, "bad.keymap"), "/ { keymap { compatible = \"zmk,keymap\"; l { bindings = <&kp A>; }; }; };");
    await expect(importLayout(e.app, { board: "moergo/glove80", source: join(e.root, "bad.keymap") })).rejects.toThrow(UsageError);
    await expect(importLayout(e.app, { board: "moergo/glove80", source: join(e.root, "bad.keymap") })).rejects.toThrow("This keymap has 1 keys, and the MoErgo Glove80 has 80.");
    await expect(importLayout(e.app, { board: "moergo/glove80", source: join(e.root, "nope.keymap") })).rejects.toThrow(/does not exist/);
  });

  // R11-09: a 42-key Corne keymap dropped on the Keebart Corne's card was refused in board ids, with nothing but Start blank.
  test("a keymap with another ZMK board's number of keys names both boards and the board it fits", async () => {
    const e = await zmkEnv();
    const { importLayout } = await import("../../src/app/index.ts");
    const refused = await importLayout(e.app, { board: "keebart/corne-choc-pro-bt", source: "test/fixtures/zmk/corne/corne.keymap" }).then(() => null, (err: unknown) => err);
    expect(refused).toBeInstanceOf(BoardRefusal);
    expect(refused).toMatchObject({ code: "keymap_for_other_board", board: "foostan/corne" });
    expect((refused as Error).message).toStartWith("This keymap has 42 keys, and the Keebart Corne Choc Pro BT has 46. It fits the foostan Corne");
    // The same file on the board it fits imports.
    expect((await importLayout(e.app, { board: "foostan/corne", source: "test/fixtures/zmk/corne/corne.keymap" })).report.keysPerLayer).toBe(42);
  });

  // PR #318 review: base at 46 and nav at 42 was offered "It fits the foostan Corne", whose card then offered the Keebart Corne back.
  test("a keymap whose layers disagree on their number of keys offers no board", async () => {
    const e = await zmkEnv();
    const { importLayout } = await import("../../src/app/index.ts");
    const row = (n: number) => Array(n).fill("&kp A").join(" ");
    await Bun.write(join(e.root, "mixed.keymap"), `/ { keymap { compatible = "zmk,keymap"; base { bindings = <${row(46)}>; }; nav { bindings = <${row(42)}>; }; }; };`);
    for (const board of ["keebart/corne-choc-pro-bt", "foostan/corne"]) {
      const refused = await importLayout(e.app, { board, source: join(e.root, "mixed.keymap") }).then(() => null, (err: unknown) => err);
      expect(refused).toBeInstanceOf(UsageError);
      expect(refused).not.toBeInstanceOf(BoardRefusal);
      expect((refused as Error).message).toStartWith("This keymap's layers don't have the same number of keys (base has 46, nav has 42)");
      expect((refused as Error).message).not.toContain("It fits");
    }
  });

  // PR #318 review: `.find` offered whichever board was listed first when two ZMK boards share a count.
  test("a keymap that fits several ZMK boards offers none over the others, and names each", async () => {
    const { keyCountRefusal } = await import("../../src/app/layouts.ts");
    const { ZmkKeyCountError } = await import("../../src/firmware/zmk/import.ts");
    const { listBoardDefinitions } = await import("../../src/app/boards.ts");
    const boards = listBoardDefinitions();
    const keebart = boards.find((b) => b.definition.id === "keebart/corne-choc-pro-bt");
    const corne = boards.find((b) => b.definition.id === "foostan/corne");
    if (keebart === undefined || corne === undefined) throw new Error("expected both Cornes");
    const copy = { ...corne, definition: { ...corne.definition, id: "me/corne-copy", vendor: "Me", name: "Corne copy" } };
    const err = new ZmkKeyCountError(42, "This keymap has 42 keys, and the Keebart Corne Choc Pro BT has 46.");
    const refused = keyCountRefusal(err, keebart, [...boards, copy]);
    expect(refused).not.toBeInstanceOf(BoardRefusal);
    expect(refused.message).toBe("This keymap has 42 keys, and the Keebart Corne Choc Pro BT has 46. It fits the foostan Corne or the Me Corne copy.");
    // One board with that count is still offered.
    expect(keyCountRefusal(err, keebart, boards)).toMatchObject({ code: "keymap_for_other_board", board: "foostan/corne" });
  });

  test("a keymap no ZMK board keyloom knows fits is a plain usage error naming both counts", async () => {
    const e = await zmkEnv();
    const { importLayout } = await import("../../src/app/index.ts");
    await Bun.write(join(e.root, "three.keymap"), "/ { keymap { compatible = \"zmk,keymap\"; l { bindings = <&kp A &kp B &kp C>; }; }; };");
    const refused = await importLayout(e.app, { board: "foostan/corne", source: join(e.root, "three.keymap") }).then(() => null, (err: unknown) => err);
    expect(refused).toBeInstanceOf(UsageError);
    expect(refused).not.toBeInstanceOf(BoardRefusal);
    expect((refused as Error).message).toBe("This keymap has 3 keys, and the foostan Corne has 42.");
  });
});

describe("build", () => {
  test("starts at once, then succeeds with a .uf2 under the data directory, in the shape the server returns", async () => {
    const e = await zmkEnv();
    await e.run(async () => {
      const started = await startBuild(e.app, "glove80");
      expect(started).toMatchObject({ status: "running", artifactPath: null, boardRevision: "default" });
      const done = await until(() => getBuild(e.app, started.id), (b) => b.status !== "running");
      expect(done.status).toBe("succeeded");
      expect(done.artifactPath).toBe(join(e.dataDir, "artifacts", `${started.id}.uf2`));
      expect(Buffer.from(await Bun.file(done.artifactPath as string).bytes())).toEqual(Buffer.from(combinedUf2()));
      expect(done.logTail.join("\n")).toContain("2 images");
      expect(() => BuildSchema.parse(done)).not.toThrow();
      // The generated files went into the template checkout where its Nix build reads them.
      expect(await Bun.file(join(e.checkout, "config", "glove80.keymap")).text()).toContain(`Generated by keyloom from ${e.imported.revisionId}`);
      const calls = await Bun.file(e.vars.FAKE_DOCKER_LOG).text();
      expect(calls).toContain(imageTag("ce69e85f585c724142aae37ddf8a7e019ff19e93"));
    });
  });

  test("a compile error fails the build with the layer and position, and exit 7's error carries the log path", async () => {
    const e = await zmkEnv();
    await e.run(async () => {
      const err = (await buildAndWait(e.app, "glove80").catch((x) => x)) as BuildFailedError;
      expect(err).toBeInstanceOf(BuildFailedError);
      expect(err.message).toMatch(/The generated keymap doesn't compile: 'NOPE' undeclared at line 3 of glove80\.keymap/);
      expect(err.logPath).toContain("build-bld_");
    }, { FAKE_MODE: "compile", FAKE_LINE: "3", FAKE_COL: "1" });
  });

  test("Docker not running fails before anything is cloned or built", async () => {
    const e = await zmkEnv();
    await e.run(async () => {
      const err = (await buildAndWait(e.app, "glove80").catch((x) => x)) as BuildFailedError;
      expect(err.message).toMatch(/Docker daemon isn't running/);
    }, { FAKE_MODE: "nodaemon" });
  });
});

describe("flash", () => {
  async function built(e: Awaited<ReturnType<typeof zmkEnv>>) {
    return e.run(() => buildAndWait(e.app, "glove80"));
  }

  test("flashes the right half and then the left into the volumes directory, telling the person what to do for each", async () => {
    const e = await zmkEnv();
    const b = await built(e);
    const boot = fakeBootloaders(e.volumes, [RIGHT, LEFT], { onDemand: "all" });
    const seen: string[] = [];
    const f = await flashAndWait(e.app, {
      buildId: b.id, volumesRoot: e.volumes, bootloaderWaitMs: 5000,
      onState: (v) => {
        if (v.instruction && seen.at(-1) !== v.instruction) seen.push(v.instruction);
        if (v.instruction?.includes("Flash the right half")) boot.mount(RIGHT);
        if (v.instruction?.includes("Flash the left half")) boot.mount(LEFT);
      },
    });
    boot.stop();
    expect(f.status).toBe("succeeded");
    expect(boot.written).toEqual([RIGHT, LEFT]);
    // Before the flasher has looked at the serial ports nothing can be asked of the person; these halves run no keyloom firmware, so then the key combo is.
    expect(seen[0]).toContain("checking whether it can restart");
    expect(seen.find((s) => s.includes("right half"))).toContain("Flash the right half (1 of 2)");
    expect(seen.some((s) => s.includes("Don't unplug"))).toBe(true);
    expect(seen.find((s) => s.includes("left half"))).toContain("Flash the left half (2 of 2)");
    expect(f.instruction).toBeNull();
    expect(() => FlashSchema.parse(f)).not.toThrow();
  });

  // The desktop app kills a server that takes over 30 s to stop; the left half's wait would hold the shutdown for its whole length.
  test("shutdown cancels a split flash whose second half waits for a hand, though its first half was written", async () => {
    const e = await zmkEnv();
    const b = await built(e);
    const boot = fakeBootloaders(e.volumes, [RIGHT, LEFT], { mountAfterMs: [100], onDemand: true });
    const started = await startFlash(e.app, { buildId: b.id, volumesRoot: e.volumes, bootloaderWaitMs: 60_000 });
    await until(() => getFlash(e.app, started.id), (v) => v.instruction?.includes("Flash the left half") === true);
    const drained = await Promise.race([drainManualFlashTasks(e.app).then(() => "drained"), Bun.sleep(8000).then(() => "still waiting")]);
    boot.stop();
    expect(drained).toBe("drained");
    expect(boot.written).toEqual([RIGHT]);
    const done = await getFlash(e.app, started.id);
    expect(done.status).toBe("failed");
    expect(done.error).toContain("The halves flashed so far keep the new firmware");
  }, 30_000);

  // A shutdown that lands while the first half is written must still end the flash when the second half waits, not wait that half out.
  test("shutdown during the first half's write cancels the flash once the second half waits for a hand", async () => {
    const e = await zmkEnv();
    const b = await built(e);
    const boot = fakeBootloaders(e.volumes, [RIGHT, LEFT], { mountAfterMs: [100], onDemand: true });
    let draining: Promise<string> | undefined;
    const started = await startFlash(e.app, {
      buildId: b.id, volumesRoot: e.volumes, bootloaderWaitMs: 60_000,
      onFlasherState: (state) => {
        if (state === "writing") draining ??= drainManualFlashTasks(e.app).then(() => "drained");
      },
    });
    await until(async () => draining, (d) => d !== undefined);
    const drained = await Promise.race([draining as Promise<string>, Bun.sleep(8000).then(() => "still waiting")]);
    boot.stop();
    expect(drained).toBe("drained");
    expect(boot.written).toEqual([RIGHT]);
    const done = await getFlash(e.app, started.id);
    expect(done.status).toBe("failed");
    expect(done.error).toContain("The halves flashed so far keep the new firmware");
  }, 30_000);

  test("the flash view shows the instruction for the half it is waiting for, as the web app polls it", async () => {
    const e = await zmkEnv();
    const b = await built(e);
    const started = await startFlash(e.app, { buildId: b.id, volumesRoot: e.volumes, bootloaderWaitMs: 400 });
    expect(started.status).toBe("waiting_for_bootloader");
    const polled = await until(() => getFlash(e.app, started.id), (v) => v.instruction?.includes("Flash the right half") === true);
    expect(polled.instruction).toContain("Flash the right half (1 of 2)");
    const done = await until(() => getFlash(e.app, started.id), (v) => v.status === "failed");
    expect(done.error).toContain("GLV80RHBOOT didn't appear");
    expect(done.instruction).toBeNull();
  });

  test("a bootloader that never appears fails the flash (exit 8) and nothing is written anywhere", async () => {
    const e = await zmkEnv();
    const b = await built(e);
    const err = (await flashAndWait(e.app, { buildId: b.id, volumesRoot: e.volumes, bootloaderWaitMs: 150 }).catch((x) => x)) as FlashFailedError;
    expect(err).toBeInstanceOf(FlashFailedError);
    expect(err.message).toContain("Nothing was flashed");
  });

  test("a flash that forgets its volumes root can't reach the real one under test", async () => {
    const e = await zmkEnv();
    const b = await built(e);
    const err = (await flashAndWait(e.app, { buildId: b.id, bootloaderWaitMs: 150 }).catch((x) => x)) as FlashFailedError;
    expect(err).toBeInstanceOf(FlashFailedError);
    expect(err.message).toContain("tests must flash into a temporary directory");
  });

  test("the editor backend builds and flashes a Glove80 layout the same way as a Moonlander", async () => {
    const e = await zmkEnv();
    const backend = appEditorBackend(e.app, { volumesRoot: e.volumes, bootloaderWaitMs: 5000 });
    await e.run(async () => {
      const revisionId = getLayout(e.app, "glove80").revision.id;
      const build = await backend.startBuild("glove80", { revisionId });
      const done = await until(async () => (await backend.getBuild(build.id))!, (b) => b.status !== "running");
      expect(done.status).toBe("succeeded");
      const boot = fakeBootloaders(e.volumes, [RIGHT, LEFT], { mountAfterMs: [100, 700] });
      const flash = await backend.startFlash(build.id);
      const finished = await until(async () => (await backend.getFlash(flash.id))!, (f) => f.status === "succeeded" || f.status === "failed", 15_000);
      boot.stop();
      expect(finished.status).toBe("succeeded");
      expect(boot.written).toEqual([RIGHT, LEFT]);
    });
  });
});
